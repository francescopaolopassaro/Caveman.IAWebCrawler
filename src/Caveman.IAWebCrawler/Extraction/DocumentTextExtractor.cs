using System.IO.Compression;
using System.Net;
using System.Text;
using System.Text.RegularExpressions;
using AngleSharp.Html.Parser;
using Stilo.Documents.Converters;
using Stilo.Documents.Images;

namespace Caveman.IAWebCrawler.Extraction;

/// <summary>
 /// Extracts the readable content of the downloaded files so it lands in the RAG
 /// corpus (not just the URL, but the content). The heavy conversions are handled by
 /// <c>Stilo.Documents</c> (100% managed):
/// <list type="bullet">
 /// <item><b>pdf</b> - PdfToHtmlConverter -> HTML -> text/paragraphs.</item>
 /// <item><b>docx/dotx</b> - DocxToHtmlConverter -> HTML -> text.</item>
 /// <item><b>csv/tsv/txt/json/xml/ics/kml</b> - plain text.</item>
 /// <item><b>odt/ods/odp</b> - fallback: XML inside the ODF archive.</item>
/// </list>
 /// For images (jpeg/png/jpg/gif...) <see cref="InspectImage"/> uses
 /// <c>Stilo.Documents.Images.DocumentImage.Identify</c>: format, size and metadata.
/// </summary>
public static partial class DocumentTextExtractor
{
    // ------------------------------------------------------------ documenti

    /// <summary>
     /// Extracts the text of a document downloaded in memory. Returns an empty string
     /// when the type is not supported: the RAG still registers the document as a resource.
    /// </summary>
    public static async Task<string> ExtractAsync(byte[] bytes, string ext, string contentType,
        int maxChars, CancellationToken ct = default)
    {
        ext = ext.ToLowerInvariant();
        if (bytes.Length == 0) return "";
        try
        {
            switch (ext)
            {
                case "pdf":
                case "docx" or "dotx":
                    return Limit(await StiloTextAsync(bytes, ext, ct), maxChars);

                case "csv" or "tsv" or "txt" or "json" or "xml"
                     or "ics" or "kml" or "rtf" or "md":
                    return Limit(PlainText(bytes), maxChars);

                case "odt" or "ods" or "odp":
                    return Limit(OdfText(bytes), maxChars);

                default:
                     // coverage for types without an extension but with a textual content-type
                    if (contentType.StartsWith("text/", StringComparison.OrdinalIgnoreCase) ||
                        contentType.Contains("json", StringComparison.OrdinalIgnoreCase) ||
                        contentType.Contains("xml", StringComparison.OrdinalIgnoreCase))
                        return Limit(PlainText(bytes), maxChars);
                    return "";
            }
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            return ""; // corrupted document or unexpected format: registered without text
        }
    }

     /// <summary>PDF and DOCX: Stilo -> HTML -> text. For PDFs it uses a dedicated parser
     /// that rebuilds the lines (spans positioned by Stilo, top/left coordinates).</summary>
    private static async Task<string> StiloTextAsync(byte[] bytes, string ext, CancellationToken ct)
    {
        await using var ms = new MemoryStream(bytes);
        var html = ext == "pdf"
            ? await new PdfToHtmlConverter().ConvertAsync(ms, ct)
            : await new DocxToHtmlConverter().ConvertAsync(ms, ct);
        if (html.Length == 0) return "";
        return ext == "pdf" ? PdfHtmlToText(html) : HtmlToPlainText(html);
    }

    /// <summary>
     /// Text from HTML generated by <c>PdfToHtmlConverter</c>: each visual line is a
     /// <c>&lt;span&gt;</c> with a top/left pt style inside <c>.stilo-pdf-page</c>.
     /// Lines are grouped by vertical coordinate and sorted horizontally,
     /// so the text reads smoothly instead of gluing the sentences together.
    /// </summary>
    private static string PdfHtmlToText(string html)
    {
        var doc = new HtmlParser().ParseDocument(html);
        var pages = doc.QuerySelectorAll(".stilo-pdf-page");
        if (pages.Length == 0) return HtmlToPlainText(html); // unexpected layout

        var sb = new StringBuilder();
        foreach (var page in pages)
        {
            var lines = new List<(double Top, double Left, string Text)>();
            foreach (var el in page.QuerySelectorAll("span"))
            {
                var txt = WebUtility.HtmlDecode(el.TextContent).Replace('\u00a0', ' ').Trim();
                if (txt.Length == 0) continue;
                var style = el.GetAttribute("style") ?? "";
                lines.Add((Coord(TopCoord(), style), Coord(LeftCoord(), style), txt));
            }
            if (lines.Count == 0) continue;

             // lines: same vertical band (+/-1.2pt); inside the line sorted by the left edge
            lines.Sort((a, b) => a.Top != b.Top ? a.Top.CompareTo(b.Top) : a.Left.CompareTo(b.Left));
            double rowTop = double.NaN;
            foreach (var line in lines)
            {
                if (double.IsNaN(rowTop) || Math.Abs(line.Top - rowTop) > 1.2)
                {
                    if (sb.Length > 0) sb.Append('\n');
                    rowTop = line.Top;
                    sb.Append(line.Text);
                }
                else
                {
                    sb.Append(' ').Append(line.Text);
                }
            }
            sb.Append("\n\n"); // separator between the PDF pages
        }

        var text = Spaces().Replace(sb.ToString(), " ");
        return MultiNewline().Replace(text, "\n").Trim();
    }

     /// <summary>Value "###.##pt" for the requested property in the inline style; 0 when missing.</summary>
    private static double Coord(Regex rx, string style)
    {
        var m = rx.Match(style);
        return m.Success && double.TryParse(m.Groups[1].Value, System.Globalization.CultureInfo.InvariantCulture,
            out var v) ? v : 0;
    }

    /// <summary>From HTML to clean text: typographic blocks (headings, paragraphs, list items, table cells).</summary>
    private static string HtmlToPlainText(string html)
    {
        var doc = new HtmlParser().ParseDocument(html);
        foreach (var el in doc.QuerySelectorAll("script, style, head, noscript"))
            el.Remove();

        var blocks = doc.QuerySelectorAll("h1, h2, h3, h4, h5, h6, p, li, blockquote, td, th, dt, dd, title");
        var body = string.Join("\n", blocks.Select(b => WebUtility.HtmlDecode(b.TextContent)
            .Replace('\u00a0', ' ').Trim())
            .Where(t => t.Length > 0));

         // "flat" documents without blocks (PDF with inline text only): the TextContent is used
        if (body.Length == 0)
            body = WebUtility.HtmlDecode(doc.Body?.TextContent ?? "")
                .Replace('\u00a0', ' ').Trim();

         // normalize: repeated spaces and multiple newlines
        body = Spaces().Replace(body, " ");
        return MultiNewline().Replace(body, "\n").Trim();
    }

    // ---------------------------------------------------------------- odf

    private static string OdfText(byte[] bytes)
    {
        using var ms = new MemoryStream(bytes);
        using var zip = new ZipArchive(ms);
        var entry = zip.GetEntry("content.xml");
        if (entry is null) return "";

        using var sr = new StreamReader(entry.Open(), Encoding.UTF8);
        var xml = sr.ReadToEnd();
        xml = ParagraphEnd().Replace(xml, "\n");
        var text = XmlTag().Replace(xml, " ");
        return WebUtility.HtmlDecode(text).Replace('\u00a0', ' ').Trim();
    }

     // ------------------------------------------------------------------- texts

    private static string PlainText(byte[] bytes)
    {
         // UTF-8 with explicit BOM; Latin1 fallback when it does not decode
        try { return StripBom(new UTF8Encoding(false, true).GetString(bytes)); }
        catch { return StripBom(Encoding.Latin1.GetString(bytes)); }
    }

    private static string StripBom(string s) =>
        s.Length > 0 && s[0] == '\ufeff' ? s[1..] : s;

    private static string Limit(string text, int maxChars)
    {
        text = text.Trim();
        if (text.Length <= maxChars) return text;
        return text[..maxChars] + "\n\n[estratto troncato alle dimensioni consentite]";
    }

    // -------------------------------------------------------------- immagini

     /// <summary>Image facts read with Stilo.Documents.Images (no OCR).</summary>
    public sealed record ImageFacts(string Format, int Width, int Height);

    /// <summary>
     /// Identifies the format and size of an image via
     /// <c>Stilo.Documents.Images.DocumentImage.Identify</c> (officially for jpg/jpeg/png,
     /// bmp, gif and other supported formats). Null when the bytes are not a readable image.
    /// </summary>
    public static ImageFacts? InspectImage(byte[] bytes)
    {
        try
        {
            var info = DocumentImage.Identify(bytes, out var format);
            return new ImageFacts(format?.Name ?? "unknown", info.Width, info.Height);
        }
        catch
        {
            return null;
        }
    }

    [GeneratedRegex(@"</w:p>|</text:p>")]
    private static partial Regex ParagraphEnd();

    [GeneratedRegex("<[^>]+>")]
    private static partial Regex XmlTag();

    [GeneratedRegex(" {2,}")]
    private static partial Regex Spaces();

    [GeneratedRegex(@"\n{3,}")]
    private static partial Regex MultiNewline();

    [GeneratedRegex(@"top:\s*(-?[\d.]+)pt")]
    private static partial Regex TopCoord();

    [GeneratedRegex(@"left:\s*(-?[\d.]+)pt")]
    private static partial Regex LeftCoord();
}
